// Builds apps-script/Code.gs: the core logic with types stripped, then the Sheets glue.
// Apps Script has no modules, so the exports become plain top-level functions.
import { stripTypeScriptTypes } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const core = readFileSync(new URL("../src/core/reminders.ts", import.meta.url), "utf8");
// Strip mode keeps comments and layout; it blanks the types with spaces, so tidy those up.
const js = stripTypeScriptTypes(core)
  .replace(/(\S) {2,}([,)])/g, "$1$2")
  .replace(/(\S) {2,}([={])/g, "$1 $2");
const plain = js.replace(/^export /gm, "").replace(/^\s*export \{\s*\};?\s*$/gm, "").replace(/[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n");
const glue = readFileSync(new URL("../apps-script/main.gs.js", import.meta.url), "utf8");
const header = "// Sheet Reminders: payment reminders from a Google Sheet. Created by Aarov Makhija.\n// Paste this whole file into Extensions > Apps Script, save, reload the sheet, then Reminders > Set up.\n// Generated by scripts/build-gs.mjs. Edit src/core/reminders.ts or apps-script/main.gs.js instead.\n\n";
writeFileSync(new URL("../apps-script/Code.gs", import.meta.url), header + plain.trim() + "\n\n" + glue);
console.log("apps-script/Code.gs written");
